#pragma once

// T06 internal tile-task contract for the shared multi-mode PE pool.
//
// This header defines the *internal* task/config/response types used by the
// Panel-LU architecture prototype. It does not change the external
// Command/Descriptor/Completion schema v2 binary layout (32B/64B/64B) and it
// does not define a numerical backend: the prototype is marked
// architecture_prototype / numerical_validation=not_performed.
//
// Status codes are reused from hw::command::StatusCode; no new status enum is
// introduced here. Buffer handles are reused from hw::dataplane::BufferHandle.

#include <cstdint>
#include <string>
#include <vector>

#include "command_codec.hpp"
#include "dataplane/buffer_manager.hpp"
#include "panel_lu/gemm_types.hpp"

namespace hw::panel_lu {

using StatusCode = hw::command::StatusCode;

// Internal tile task modes generated by the Panel controller. LU_DIAG
// factorizes one diagonal tile, TRSM_LEFT solves U12 = L11^-1 * A12,
// TRSM_RIGHT solves L21 = A21 * U11^-1, GEMM_UPDATE applies the panel-internal
// A22 -= L21 * U12 update and GEMM_SCHUR is the T10 top-level Schur update
// A22 := A22 - L21 * U12 (same math, separate mode so the INT32 backend is
// bound to the top-level command only). All modes share the same homogeneous
// PE pool.
enum class TileMode : std::uint8_t {
    LuDiag = 0,
    TrsmLeft = 1,
    TrsmRight = 2,
    GemmUpdate = 3,
    GemmSchur = 4,
};

const char* tile_mode_name(TileMode mode);

// Tile lifecycle inside a PE task slot. Queued/Blocked live in the dispatcher,
// the rest live in the PE.
enum class TaskPhase : std::uint8_t {
    Queued = 0,      // in dispatcher queue, dependencies not necessarily ready
    Blocked = 1,     // ready except for a scheduling resource (PE/slot/port)
    Dispatched = 2,  // accepted by a PE task slot (load may start)
    Loading = 3,     // operands streaming from tile store into the slot FIFO
    ReadyWait = 4,   // operands complete, fixed load latency still pending
    Ready = 5,       // waiting for the shared array
    Running = 6,     // occupying the array
    ExecDone = 7,    // array done, waiting for a writeback reservation
    Writeback = 8,   // writing the result tile back
    Done = 9,        // terminal, response pending or already delivered
    Failed = 10,
    Cancelled = 11,
};

const char* task_phase_name(TaskPhase phase);

// Effective dimensions of a task, 1..16. Zero means "no operand".
struct TileDims {
    std::uint32_t m{0};
    std::uint32_t n{0};
    std::uint32_t k{0};
};

// Data-view tags for the tile version key space. A key identifies
// (front buffer slot, data view, tile index) and distinguishes sub-block views
// from the full-front grid so A12/A21 tiles can never alias A11 tiles.
enum class TileViewTag : std::uint32_t {
    FrontGrid = 0,  // A11 and other tiles addressed on the full-front grid
    A12 = 1,        // pivot rows x update columns
    A21 = 2,        // update rows x pivot columns
    A22 = 3,        // update x update (future top-level Schur)
};

inline std::uint64_t tile_version_key(
    std::uint32_t slot,
    TileViewTag tag,
    std::uint32_t index) {
    return (static_cast<std::uint64_t>(slot) << 48) |
           (static_cast<std::uint64_t>(tag) << 32) |
           (static_cast<std::uint64_t>(index) + 1);
}

// Valid row/column counts inside the physical 16x16 tile (tail mask).
struct TileMask {
    std::uint32_t rows{0};
    std::uint32_t cols{0};
};

// One operand of a tile task: a buffer handle, element offset/stride, the
// committed version that must be visible before the task may run, and a
// version-table key. T06's synthetic prototype uses one store slot per tile
// (key = slot); the T07 real engine uses one front buffer slot per front with
// strided tile views (key = slot/index composite).
struct TileOperand {
    hw::dataplane::BufferHandle handle{};
    std::uint64_t offset{0};         // byte offset inside the slot
    std::uint32_t stride_bytes{0};   // row stride in bytes
    std::uint32_t version{0};        // required committed version
    std::uint64_t version_key{0};    // key into the tile version table
    bool valid{false};
};

// Internal tile task descriptor. Generated by the Panel controller, consumed
// by the dispatcher and executed by one multi-mode PE.
struct TileTask {
    std::uint64_t task_id{0};    // unique within the prototype run
    std::uint64_t epoch{0};      // reset generation
    std::uint32_t command_id{hw::command::NONE};
    std::uint32_t node_id{hw::command::NONE};
    std::uint32_t step{0};       // panel step (pivot tile index)
    std::uint32_t tile_row{0};   // tile coordinates inside the A11 tile grid
    std::uint32_t tile_col{0};
    TileMode mode{TileMode::GemmUpdate};

    TileOperand dst;  // target/accumulator tile
    TileOperand lhs;  // first input operand (L for left, A for right)
    TileOperand rhs;  // second input operand (A for left, U for right)

    TileDims dims;   // effective M/N/K (each <= tile_dim)
    TileMask mask;   // valid rows/cols inside the physical tile

    // PE group that owns this task's command. The dispatcher only dispatches
    // to PEs of this group; a command never steals another group's PEs.
    std::uint32_t group_id{0};
    std::vector<std::uint64_t> deps;  // task ids that must commit first
    std::uint32_t output_version{0};  // dst version after successful commit
    std::uint32_t pivot_base{0};      // global first pivot column (LU_DIAG)
    std::uint32_t sequence{0};        // generation order inside the command
    // Exact front scale and threshold product, computed in binary64 from the
    // latched FP32 front maxabs and the binary32 threshold ratio. The product
    // is exact in binary64 (24-bit x 24-bit mantissas).
    double front_pre_elimination_max_abs{0.0};
    double threshold_product{0.0};
    // T10 top-level Schur backend and scale policy. Only meaningful for
    // TileMode::GemmSchur; panel-internal GemmUpdate tasks stay FP32.
    GemmBackend gemm_backend{GemmBackend::Fp32Device};
    GemmScalePolicy gemm_scale;
};

// Terminal task response. Times are absolute prototype cycles (cycle 0 is the
// first tick).
struct TileTaskResponse {
    std::uint64_t task_id{0};
    std::uint64_t epoch{0};
    std::uint32_t command_id{hw::command::NONE};
    std::uint32_t node_id{hw::command::NONE};
    std::uint32_t step{0};
    std::uint32_t tile_row{0};
    std::uint32_t tile_col{0};
    TileMode mode{TileMode::GemmUpdate};
    std::uint32_t pe_id{0};
    std::uint32_t slot{0};
    StatusCode status{StatusCode::Ok};
    std::string reason;
    std::uint32_t failed_column{0};  // first failing column for LU_DIAG
    bool result_visible{false};      // false for aborted/cancelled tasks
    std::uint64_t enqueue_cycle{0};
    std::uint64_t dispatch_cycle{0};
    std::uint64_t load_done_cycle{0};
    std::uint64_t exec_start_cycle{0};
    std::uint64_t exec_done_cycle{0};
    std::uint64_t writeback_done_cycle{0};
    std::uint64_t bytes_read{0};
    std::uint64_t bytes_written{0};
    std::uint64_t stall_dependency_cycles{0};
    std::uint64_t stall_resource_cycles{0};
    std::uint64_t stall_port_cycles{0};
    std::uint64_t stall_writeback_cycles{0};
    // T10 INT32 GEMM bookkeeping (internal only; zero for every FP32 mode).
    GemmBackend gemm_backend{GemmBackend::Fp32Device};
    GemmPhase gemm_failed_phase{GemmPhase::None};
    std::uint32_t gemm_failed_local_row{0};
    std::uint32_t gemm_failed_local_col{0};
    std::int32_t gemm_exponent_a{0};
    std::int32_t gemm_exponent_b{0};
    std::uint64_t saturation_count{0};
    std::uint64_t overflow_count{0};
    std::uint64_t local_conversion_bytes{0};
    std::uint64_t scale_reduction_cycles{0};
    std::uint64_t quantize_cycles{0};
    std::uint64_t integer_compute_cycles{0};
    std::uint64_t dequantize_cycles{0};
};

// PE timing parameters. All values are architecture-model parameters derived
// from the documented dataflow (16x16 output-stationary array, one k-slice per
// cycle, one accumulator row drained per cycle, corner divide/reciprocal ALU
// with a fixed latency). They are *not* synthesis-calibrated and must not be
// quoted as measured silicon performance.
//
// LU_DIAG feedback chain: stage j (pivot j) cannot start until the previous
// stage's reciprocal/divide result has driven the rank-1 update that produces
// pivot j on the diagonal. The stage initiation interval is therefore
// div_latency_cycles + lu_update_cycles (a real data dependency; a pipelined
// divider with II=1 does not remove it). The successful critical path is
// (k-1) stage intervals plus one final pivot check; a failure at local column
// f costs f stage intervals plus the pivot check that detects it.
struct PeTimingConfig {
    std::uint32_t array_dim{16};        // fixed 16x16 decision
    std::uint32_t mac_lanes{256};       // 16x16 FMAC
    std::uint32_t fill_cycles{2};       // pipeline fill for GEMM/TRSM
    std::uint32_t gemm_k_ii{1};         // k-slice initiation interval
    std::uint32_t drain_row_cycles{1};  // accumulator row readout
    std::uint32_t div_latency_cycles{8};
    std::uint32_t lu_update_cycles{1};  // rank-1 update beat to reach next pivot
    std::uint32_t lu_pivot_check_cycles{1};  // zero/threshold/non-finite compare
    std::uint32_t tsolve_fill_cycles{2};
};

// Compute-command kind handled by the shared compute engine. One accepted
// command owns one PE group for its whole execution context.
enum class ComputeKind : std::uint8_t {
    PanelLu = 0,
    TrsmLeft = 1,
    TrsmRight = 2,
    GemmSchur = 3,
    // Future: solve forward/backward.
};

const char* compute_kind_name(ComputeKind kind);

// Numeric execution mode of the panel engine. Fp32Device is the production
// device path; Fp64Diagnostic is an EXPLICIT module diagnostic mode that runs
// the same algorithms with binary64 accumulators and rounds results back to
// binary32 storage. It is never selected automatically (no fallback), never
// changes command/token semantics, and must be declared in run reports.
enum class PanelNumericMode : std::uint8_t {
    Fp32Device = 0,
    Fp64Diagnostic = 1,
};

const char* panel_numeric_mode_name(PanelNumericMode mode);

// Prototype resource configuration. pe_count is the physical number of
// homogeneous PEs; Panel/TRSM/GEMM tasks compete for the same pool.
struct PanelLuConfig {
    // Compute grouping (authoritative resource description): the device owns
    // ONE physical PE pool organized as compute_group_count groups of
    // pes_per_group homogeneous PEs. A single accepted compute command owns
    // one group; group members work on different tiles of that command.
    std::uint32_t compute_group_count{2};
    std::uint32_t pes_per_group{2};
    // Compatibility field: 0 = derived from the product; any other value must
    // equal compute_group_count * pes_per_group (conflicts are rejected, never
    // silently ignored).
    std::uint32_t pe_count{0};
    std::uint32_t task_slots_per_pe{4};
    std::uint32_t dispatcher_queue_depth{32};
    std::uint32_t max_resident_commands{2};
    std::uint32_t max_front_dim{256};
    std::uint32_t tile_dim{16};  // physical compute tile; only 16 accepted
    // PE-local operand FIFO (per PE, bytes).
    std::uint32_t pe_input_fifo_bytes{4096};
    // Shared tile-store port budgets (bytes per cycle).
    std::uint32_t load_bytes_per_cycle{64};
    std::uint32_t load_latency_cycles{2};
    std::uint32_t load_queue_depth{8};
    std::uint32_t writeback_bytes_per_cycle{64};
    std::uint32_t writeback_latency_cycles{2};
    std::uint32_t writeback_queue_depth{8};
    // Full-front scan reduction latency. Scan bytes share the unified read
    // budget above; there is no separate scan port.
    std::uint32_t scan_reduce_latency_cycles{8};
    // Response visibility hold (response backpressure model).
    std::uint32_t response_hold_cycles{0};
    PeTimingConfig timing;
    // Numeric mode: Fp32Device (default production path) or the explicit
    // Fp64Diagnostic module mode. Never auto-selected.
    PanelNumericMode numeric_mode{PanelNumericMode::Fp32Device};
    // T10 local INT32 GEMM precision/conversion parameters (only used by
    // GemmSchur tasks whose backend is Int32Gemm). Validated explicitly.
    PrecisionConfig precision;

    // Total physical PEs: the only authoritative derivation used by the
    // engine. `pe_count` is validated against this product, not merged with
    // it.
    std::uint32_t total_pe_count() const {
        return compute_group_count * pes_per_group;
    }
    // PE ids of one group (contiguous pool layout).
    std::uint32_t group_first_pe(std::uint32_t group_id) const {
        return group_id * pes_per_group;
    }
};

// Capability check result for configs / tasks / front descriptors.
struct ConfigCheck {
    bool ok{false};
    StatusCode status{StatusCode::Ok};
    std::string reason;
};

// Validates the whole resource configuration. Any configuration that can not
// make progress (zero queues, zero PEs, unsupported tile size) is rejected up
// front with an explicit status instead of running forever.
ConfigCheck validate_panel_config(const PanelLuConfig& config);

// ---------------------------------------------------------------------------
// Boundary conversion: the shared PE pool still moves the internal TileTask
// representation (one homogeneous dispatcher for every mode), while the GEMM
// controller exposes the unified GemmReq/GemmRsp contract to the layers above
// it. A future RTL GEMM backend can be swapped behind the same records without
// touching the GCU/front flow.
// ---------------------------------------------------------------------------

GemmReq make_gemm_req(
    const TileTask& task,
    std::uint32_t descriptor_id,
    std::uint32_t front_dim,
    std::uint32_t pivot_dim);
GemmRsp make_gemm_rsp(
    const TileTask& task,
    const TileTaskResponse& response,
    std::uint32_t front_dim,
    std::uint32_t pivot_dim);

// Validates one internal task: modes, dimensions, masks, tile_size relation.
// Unsupported dimensions are rejected, never silently truncated.
ConfigCheck validate_tile_task(const TileTask& task, const PanelLuConfig& config);

// Front capability precheck used before a command is admitted. tile_size must
// be exactly tile_dim (16); other values are rejected explicitly. Returns
// POLICY_NOT_SUPPORTED for DYNAMIC_PANEL (not implemented in T06).
ConfigCheck check_front_capability(
    std::uint32_t front_dim,
    std::uint32_t pivot_dim,
    std::uint32_t tile_size,
    hw::command::PivotPolicy policy,
    const PanelLuConfig& config);

// ---------------------------------------------------------------------------
// Timing model (documented formulas; see docs/architecture/Panel-LU架构设计.md)
// ---------------------------------------------------------------------------

// Operand bytes fetched through the load port for one task (port traffic).
std::uint64_t task_load_bytes(const TileTask& task);
// Operand bytes that must stay resident in the PE input FIFO for one task.
// The target/accumulator tile has a dedicated per-slot register file and does
// not consume FIFO capacity, so a full 16x16 GEMM reserves only A+B = 2048B.
std::uint64_t task_operand_fifo_bytes(const TileTask& task);
// Result bytes written through the writeback port for one task.
std::uint64_t task_writeback_bytes(const TileTask& task);
// Array occupancy cycles for a successful task.
std::uint64_t task_exec_cycles(const TileTask& task, const PeTimingConfig& timing);
// Cycles from array start until a failing LU_DIAG pivot at
// failed_column (0-based, global) reports the failure.
std::uint64_t lu_diag_failure_cycles(
    std::uint32_t pivot_base,
    std::uint32_t failed_column,
    const PeTimingConfig& timing);

}  // namespace hw::panel_lu
